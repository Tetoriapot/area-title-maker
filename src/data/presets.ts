function makeTextStyle(
  profile: FontProfile,
  role: 'main' | 'sub',
  size: number,
  color: string,
  tracking: number,
): TextStyle {
  return {
    ...profile[role],
    size,
    color,
    letterSpacing: Math.round(size * tracking * 10) / 10,
    opacity: role === 'main' ? 1 : 0.9,
  };
}

export const PRESETS: AreaTitlePreset[] = rows.map((row) => {
  const [
    id,
    name,
    category,
    ,
    ,
    profileKey,
    layout,
    mainSize,
    subSize,
    mainTracking,
    subTracking,
    mainColor,
    subColor,
    lineColor,
    lineStyle,
    symbol,
    lineWidth,
    thickness,
    gap,
    lineOpacity,
    effectKey,
  ] = row;
  const profile = fontProfiles[profileKey];

  return {
    id,
    name,
    category,
    mainText: SAMPLE_MAIN_TEXT,
    subText: SAMPLE_SUB_TEXT,
    mainTextStyle: makeTextStyle(
      profile,
      'main',
      mainSize,
      mainColor,
      mainTracking,
    ),
    subTextStyle: makeTextStyle(profile, 'sub', subSize, subColor, subTracking),
    layout,
    decoration: {
      lineStyle,
      symbol,
      width: lineWidth,
      thickness,
      gap,
      sidePadding: 0,
      color: lineColor,
      opacity: lineOpacity,
    },
    effects: JSON.parse(
      JSON.stringify(effectProfiles[effectKey]),
    ) as EffectsSettings,
  };
});

export const PRESET_BY_ID = new Map(
  PRESETS.map((preset) => [preset.id, preset]),
);

export function applyPresetToState<
  T extends {
    mainTextStyle: TextStyle;
    subTextStyle: TextStyle;
    layout: LayoutType;
    decoration: AreaTitlePreset['decoration'];
    effects: EffectsSettings;
    presetId: string;
  },
>(state: T, preset: AreaTitlePreset): T {
  return {
    ...state,
    presetId: preset.id,
    mainTextStyle: { ...preset.mainTextStyle },
    subTextStyle: { ...preset.subTextStyle },
    layout: preset.layout,
    decoration: { ...preset.decoration },
    effects: JSON.parse(JSON.stringify(preset.effects)) as EffectsSettings,
  };
}
